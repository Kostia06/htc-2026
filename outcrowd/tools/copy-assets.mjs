#!/usr/bin/env node
// Copies every asset the homepage really uses (see tools/extract-spec.mjs ->
// .compare/spec-extract/used-assets.json) from the snapshot mirror into public/,
// downloads the ones missing from the snapshot, and writes spec/assets.json
// (original URL -> local public path).
// usage: node tools/extract-spec.mjs && node tools/copy-assets.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SNAPSHOT_DIR = process.env.SNAPSHOT_DIR || '/Users/kartikmiital/Downloads/assets';
const PUBLIC = path.join(ROOT, 'public');
const used = JSON.parse(fs.readFileSync(path.join(ROOT, '.compare', 'spec-extract', 'used-assets.json'), 'utf8'));

const folderFor = (name) => {
  const ext = path.extname(name).toLowerCase();
  if (['.woff', '.woff2', '.ttf', '.otf'].includes(ext)) return 'fonts';
  if (['.mp4', '.webm', '.mov'].includes(ext)) return 'video';
  if (['.mp3', '.wav', '.ogg'].includes(ext)) return 'audio';
  if (ext === '.json') return 'lottie';
  return 'images';
};

// Snapshot URLs are rewritten as https://www.outcrowd.io/<host>/<path>; the mirror
// folds "?query" into the file name ("name_query.ext"). Recover the original URL.
function originalUrl(u) {
  let url = new URL(u);
  if (url.hostname === 'www.outcrowd.io') {
    const m = url.pathname.match(/^\/([^/]+)(\/.*)$/);
    url = new URL(`https://${m[1]}${m[2]}`);
  }
  if (url.hostname === 'dl.dropboxusercontent.com') {
    const dec = decodeURIComponent(url.pathname);
    const m = dec.match(/^(.*)_(rlkey=.*)(\.[a-z0-9]+)$/i);
    if (m) return `https://${url.hostname}${m[1]}${m[3]}?${m[2]}`;
  }
  return url.href;
}

function mirrorFile(orig) {
  const u = new URL(orig);
  const p = path.join(SNAPSHOT_DIR, u.hostname, decodeURIComponent(u.pathname));
  if (u.search) {
    const ext = path.extname(p);
    const folded = p.slice(0, -ext.length) + '_' + decodeURIComponent(u.search.slice(1)) + ext;
    if (fs.existsSync(folded)) return folded;
  }
  return fs.existsSync(p) ? p : null;
}

const map = {};
const report = { copied: 0, downloaded: [], missing: [] };
const extra = [
  { url: 'https://dl.dropboxusercontent.com/s/03lxlbaek2ye22m/click_min.mp3', where: ['script'] },
];
for (const { url, where } of [...used, ...extra]) {
  const orig = originalUrl(url);
  const name = decodeURIComponent(path.basename(new URL(orig).pathname));
  const folder = folderFor(name);
  const dest = path.join(PUBLIC, folder, name);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  const src = mirrorFile(orig);
  if (src) {
    fs.copyFileSync(src, dest);
    report.copied++;
  } else if (!fs.existsSync(dest)) {
    const res = await fetch(orig);
    if (!res.ok) {
      report.missing.push(orig);
      continue;
    }
    fs.writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
    report.downloaded.push(orig);
  } else if (folder === 'lottie' || folder === 'audio') {
    report.downloaded.push(orig + ' (already in public/)');
  }
  map[orig] = `/${folder}/${name}`;
}

const out = {
  _note:
    'original URL (as referenced by the live outcrowd.io homepage / its CSS) -> path served from outcrowd/public. ' +
    'Generated by tools/copy-assets.mjs. split-type comes from npm, Lora from Google Fonts.',
  assets: Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b))),
};
fs.writeFileSync(path.join(ROOT, 'spec', 'assets.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`copied ${report.copied}, downloaded ${report.downloaded.length}, missing ${report.missing.length}`);
for (const d of report.downloaded) console.log('  downloaded:', d);
for (const m of report.missing) console.log('  MISSING:', m);
