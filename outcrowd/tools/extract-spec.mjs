#!/usr/bin/env node
// Designer tooling: inspects the reference snapshot in the browser and writes
//   .compare/spec-extract/used-assets.json   every asset URL the page really uses
//   spec/webflow-homepage.css                 the Webflow CSS reduced to rules that match the homepage DOM
//   .compare/spec-extract/computed-<w>.json   computed styles of key elements per viewport
// usage: node tools/extract-spec.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { launch, sleep } from './lib/capture.mjs';
import { openReference } from './reference.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, '.compare', 'spec-extract');
fs.mkdirSync(OUT, { recursive: true });

const browser = await launch();
try {
  // ---------- assets + filtered css (1440) ----------
  const { page } = await openReference(browser, 1440);
  await sleep(3000);
  const data = await page.evaluate(() => {
    const abs = (u) => {
      try {
        return new URL(u, location.href).href;
      } catch {
        return u;
      }
    };
    const assets = new Map();
    const add = (u, where) => {
      if (!u || u.startsWith('data:')) return;
      u = abs(u);
      if (!assets.has(u)) assets.set(u, new Set());
      assets.get(u).add(where);
    };
    document.querySelectorAll('img').forEach((i) => {
      add(i.getAttribute('src'), 'img');
      (i.getAttribute('srcset') || '')
        .split(',')
        .map((s) => s.trim().split(/\s+/)[0])
        .filter(Boolean)
        .forEach((u) => add(u, 'img-srcset'));
    });
    document.querySelectorAll('source[src], video[src], video[poster]').forEach((v) => {
      add(v.getAttribute('src'), 'video');
      add(v.getAttribute('poster'), 'video-poster');
    });
    document.querySelectorAll('[data-src]').forEach((e) => add(e.getAttribute('data-src'), 'lottie'));
    document.querySelectorAll('[data-poster-url]').forEach((e) => add(e.getAttribute('data-poster-url'), 'bg-video-poster'));
    document.querySelectorAll('link[rel~=icon], link[rel=apple-touch-icon]').forEach((l) => add(l.getAttribute('href'), 'icon'));
    document.querySelectorAll('meta[property="og:image"], meta[name="twitter:image"]').forEach((m) => add(m.getAttribute('content'), 'meta'));

    // CSS: keep rules whose selector matches the DOM
    const strip = (sel) =>
      sel
        .replace(/::?(before|after|placeholder|selection|-webkit-[a-z-]+|-moz-[a-z-]+|-ms-[a-z-]+|marker|first-line|first-letter)/g, '')
        .replace(/:(hover|focus|focus-visible|focus-within|active|visited|link|checked|disabled|invalid|valid|target)/g, '')
        .trim() || '*';
    const matches = (selText) =>
      selText.split(',').some((s) => {
        try {
          return !!document.querySelector(strip(s));
        } catch {
          return false;
        }
      });
    const out = [];
    const urlRe = /url\(\s*(?:"([^"]+)"|'([^']+)'|([^)'"]+))\s*\)/g;
    const walk = (rules, media, sheetHref) => {
      for (const r of rules) {
        if (r instanceof CSSMediaRule) walk(r.cssRules, r.conditionText || r.media.mediaText, sheetHref);
        else if (r instanceof CSSStyleRule) {
          if (matches(r.selectorText)) {
            out.push({ media, css: r.cssText, sheet: sheetHref });
            for (const m of r.cssText.matchAll(urlRe)) add(new URL(m[1] || m[2] || m[3], sheetHref).href, 'css');
          }
        } else if (r instanceof CSSFontFaceRule) {
          out.push({ media, css: r.cssText, sheet: sheetHref, fontface: true });
          for (const m of r.cssText.matchAll(urlRe)) add(new URL(m[1] || m[2] || m[3], sheetHref).href, 'font');
        } else if (r instanceof CSSKeyframesRule) {
          out.push({ media, css: r.cssText, sheet: sheetHref });
        }
      }
    };
    for (const sh of document.styleSheets) {
      let rules;
      try {
        rules = sh.cssRules;
      } catch {
        continue;
      }
      walk(rules, '', sh.href || location.href);
    }
    return { assets: [...assets].map(([u, w]) => ({ url: u, where: [...w] })), css: out };
  });
  fs.writeFileSync(path.join(OUT, 'used-assets.json'), JSON.stringify(data.assets, null, 2));

  // group css by sheet + media, keep source order
  const groups = [];
  for (const r of data.css) {
    const key = `${r.sheet.includes('webflow.shared') ? 'webflow.css' : r.sheet === 'https://www.outcrowd.io/' ? 'inline <style> in page' : r.sheet}|${r.media}`;
    let g = groups[groups.length - 1];
    if (!g || g.key !== key) groups.push((g = { key, rules: [] }));
    g.rules.push(r.css.replace(/url\("https:\/\/www\.outcrowd\.io\//g, 'url("https://'));
  }
  let css = `/* Webflow CSS reduced to the rules that match the homepage DOM (source order kept).\n   Generated by tools/extract-spec.mjs from the snapshot. Breakpoints: 991 / 767 / 479 (+ custom). */\n`;
  for (const g of groups) {
    const [sheet, media] = g.key.split('|');
    css += `\n/* ---- ${sheet}${media ? ' @media ' + media : ''} ---- */\n`;
    if (media) css += `@media ${media} {\n` + g.rules.map((r) => '  ' + r).join('\n') + '\n}\n';
    else css += g.rules.join('\n') + '\n';
  }
  fs.writeFileSync(path.join(ROOT, 'spec', 'webflow-homepage.css'), css);
  console.log(`assets: ${data.assets.length}, css rules kept: ${data.css.length}`);
  await page.close();
} finally {
  await browser.close();
}
